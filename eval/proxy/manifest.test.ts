import { createHash } from 'node:crypto';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

const ROOT = dirname(fileURLToPath(import.meta.url));
const MANIFEST_PATH = join(ROOT, 'manifest.json');
const CONSTRUCTION_PATH = join(ROOT, 'CONSTRUCTION.md');

interface ManifestRow {
  relpath: string;
  sha256: string;
  label: 'real' | 'ai';
  family: string;
  corruption: string;
  license: string;
}

interface Manifest {
  version: number;
  rows: ManifestRow[];
  description?: string;
}

const REQUIRED_AI_FAMILIES = [
  'sdxl',
  'flux-schnell',
  'pixart',
  'openfake',
] as const;

function sha256File(abs: string): string {
  return createHash('sha256').update(readFileSync(abs)).digest('hex');
}

describe('eval/proxy freeze (AC-FREEZE)', () => {
  it('manifest exists and is non-empty (fail-closed)', () => {
    expect(existsSync(MANIFEST_PATH)).toBe(true);
    const raw = readFileSync(MANIFEST_PATH, 'utf8');
    const manifest = JSON.parse(raw) as Manifest;
    expect(Array.isArray(manifest.rows)).toBe(true);
    expect(manifest.rows.length).toBeGreaterThan(0);
  });

  it('has >= 200 labeled hashed rows with on-disk sha match', () => {
    const manifest = JSON.parse(
      readFileSync(MANIFEST_PATH, 'utf8'),
    ) as Manifest;
    expect(manifest.rows.length).toBeGreaterThanOrEqual(200);

    for (const row of manifest.rows) {
      expect(row.sha256).toMatch(/^[a-f0-9]{64}$/);
      expect(row.label === 'real' || row.label === 'ai').toBe(true);
      expect(typeof row.relpath).toBe('string');
      expect(row.relpath.length).toBeGreaterThan(0);
      expect(typeof row.family).toBe('string');
      expect(typeof row.corruption).toBe('string');
      expect(typeof row.license).toBe('string');

      const abs = join(ROOT, row.relpath);
      expect(existsSync(abs), `missing file for ${row.relpath}`).toBe(true);
      const dig = sha256File(abs);
      expect(dig, `sha mismatch for ${row.relpath}`).toBe(row.sha256);
    }
  });

  it('has >= 100 real and >= 100 ai with four required families', () => {
    const manifest = JSON.parse(
      readFileSync(MANIFEST_PATH, 'utf8'),
    ) as Manifest;
    const real = manifest.rows.filter((r) => r.label === 'real');
    const ai = manifest.rows.filter((r) => r.label === 'ai');
    expect(real.length).toBeGreaterThanOrEqual(100);
    expect(ai.length).toBeGreaterThanOrEqual(100);

    const families = new Set(ai.map((r) => r.family));
    for (const f of REQUIRED_AI_FAMILIES) {
      expect(families.has(f), `missing AI family ${f}`).toBe(true);
    }
  });

  it('CONSTRUCTION.md exists and forbids train + subset + requires strip', () => {
    expect(existsSync(CONSTRUCTION_PATH)).toBe(true);
    const text = readFileSync(CONSTRUCTION_PATH, 'utf8');

    // AC-STRIP
    expect(text.toLowerCase()).toMatch(/metadata stripped|strip/);

    // AC-NOTRAIN
    expect(text.toLowerCase()).toMatch(/never train|forbidden.*train|not enter 4\.1 train/);

    // AC-NOSUBSET — must not allow a hashed subset for soul 7
    expect(text.toLowerCase()).toMatch(/no hashed subset|full frozen proxy|full proxy/);
    expect(text).not.toMatch(/allowed to use a hashed subset/i);
    expect(text).not.toMatch(/subset is sufficient for soul 7/i);

    // Named legal AI sources (not sine-wave stand-ins)
    expect(text).toMatch(/DRAGON/i);
    expect(text).toMatch(/OpenFake/i);
    expect(text).toMatch(/SDXL/);
    expect(text).toMatch(/Flux\.1-schnell|Flux\.1|flux-schnell/i);
    expect(text).toMatch(/PixArt/i);
    // Must not describe the freeze as using placeholder textures for family tags
    expect(text).not.toMatch(/family-tinted|placeholder texture|fake family tags are ok/i);
  });

  it('AI licenses name real generators/datasets, not procedural MIT noise', () => {
    const manifest = JSON.parse(
      readFileSync(MANIFEST_PATH, 'utf8'),
    ) as Manifest;
    const ai = manifest.rows.filter((r) => r.label === 'ai');
    for (const row of ai) {
      expect(row.license.toLowerCase()).not.toMatch(
        /self-generated by eval\/proxy\/build_images|sine|procedural noise|prng/,
      );
      expect(
        /dragon|openfake|sdxl|flux|pixart/i.test(row.license),
        `license should name source: ${row.relpath} → ${row.license}`,
      ).toBe(true);
    }
  });
});
